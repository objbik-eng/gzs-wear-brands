/* Crea un pedido en Printify en estado BORRADOR (no se fabrica ni se cobra
   hasta que lo revises y le des a "Enviar a producción"). */
export async function crearPedidoBorrador({ sessionId, email, nombre, telefono, direccion, items }) {
  const token = process.env.PRINTIFY_TOKEN;
  if (!token) return { skipped: 'PRINTIFY_TOKEN no configurado' };

  const line_items = [];
  const sinMapear = [];
  for (const it of items) {
    const p = MAP[it.product_id];
    if (!p) { sinMapear.push(it.product_id); continue; }
    const key = `${it.color}|${it.size}`;
    let vid = p.variants[key];
    if (!vid) {
      const keys = Object.keys(p.variants);
      const mismoColor = keys.find((k) => k.split('|')[0] === it.color);
      vid = p.variants[mismoColor || (keys.length === 1 ? keys[0] : '')];
    }
    if (!vid) { sinMapear.push(`${p.slug} ${it.color}/${it.size}`); continue; }
    line_items.push({ product_id: p.printify_id, variant_id: vid, quantity: it.qty });
  }
  if (!line_items.length) return { skipped: 'sin variantes válidas', sinMapear };
  if (sinMapear.length) console.error('printify: sin mapear', sinMapear);

  const partes = String(nombre || '').trim().split(/\s+/);
  const body = {
    external_id: sessionId,
    label: `GZS ${String(sessionId).slice(-8)}`,
    line_items,
    shipping_method: 1,
    send_to_production: false,          // ← borrador: lo revisas tú
    address_to: {
      first_name: partes[0] || 'Cliente',
      last_name: partes.slice(1).join(' ') || '-',
      email: email || '',
      phone: telefono || '',
      country: direccion?.country || 'ES',
      region: direccion?.state || '',
      city: direccion?.city || '',
      address1: direccion?.line1 || '',
      address2: direccion?.line2 || '',
      zip: direccion?.postal_code || '',
    },
  };

  const r = await fetch(`https://api.printify.com/v1/shops/${SHOP_ID}/orders.json`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', 'User-Agent': 'gzs-web' },
    body: JSON.stringify(body),
  });
  const data = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(`Printify ${r.status}: ${JSON.stringify(data).slice(0, 200)}`);
  return { id: data.id, estado: data.status, sinMapear };
}
